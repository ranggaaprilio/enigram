from datetime import UTC, datetime

import yaml
from test_annotations import note

from enigram.application.regression import HEADER, regression_doc

APPROVED = datetime(2026, 11, 5, 8, tzinfo=UTC)
REPOS = {
    1: {
        "id": 1,
        "url": "https://github.com/org/app",
        "ref": "eval-v1",
        "indexed_sha": "70ae60dbb609",
    }
}


def _proposal(**kw):
    values = {
        "via": "mcp",
        "author": "laptop-a",
        "owner": "laptop-a",
        "question": "Does logout revoke the refresh token?",
        "verified_by": "web",
        "verified_at": APPROVED,
    }
    return note(**{**values, **kw})


def test_regression_doc_keeps_approved_proposals_with_a_question():
    notes = [
        _proposal(id=42, memory_id=12),
        _proposal(id=40, target_kind="entity", target_ref="Refresh Token", repo_id=None),
        _proposal(id=43, status="proposed", verified_by=None, verified_at=None),
        _proposal(id=44, status="rejected"),
        _proposal(id=45, question=None),
        _proposal(id=46, via="api"),
        _proposal(id=47, status="needs_verification", reason="deps"),  # approved once: kept
        _proposal(id=48, status="proposed"),  # approved, then edited by a non-verifier key
    ]

    doc = regression_doc(notes, REPOS)

    assert doc["version"] == 1
    assert [q["id"] for q in doc["questions"]] == ["r0040", "r0042", "r0047"]
    entity, symbol, _ = doc["questions"]
    assert symbol == {
        "id": "r0042",
        "category": "behavior_annotation",
        "split": "regression",
        "expected_route": "annotation",
        "repo": {"url": "https://github.com/org/app", "ref": "eval-v1", "sha": "70ae60dbb609"},
        "setup": {
            "annotation": {
                "target": "AuthService.logout",
                "text": "Logout also revokes the refresh token.",
            }
        },
        "question": "Does logout revoke the refresh token?",
        "answer": "Logout also revokes the refresh token.",
        "evidence": [{"symbol": "AuthService.logout"}],
        "source": {
            "note": 42,
            "proposed_by": "laptop-a",
            "approved_by": "web",
            "approved_at": "2026-11-05T08:00:00+00:00",
            "memory_id": 12,
        },
    }
    assert "repo" not in entity and entity["evidence"] == []
    assert entity["setup"]["annotation"]["target"] == "Refresh Token"


def test_regression_doc_round_trips_as_yaml():
    doc = regression_doc([_proposal(id=1, text="Ünïcode: «ok»")], REPOS)
    text = HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True)

    assert text.startswith("# Generated by `enigram regression export`")
    assert yaml.safe_load(text) == doc
